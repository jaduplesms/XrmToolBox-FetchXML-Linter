$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root = Split-Path $PSScriptRoot -Parent
$assets = Join-Path $root 'assets'
$images = @{}
$source = [Drawing.Bitmap]::new((Join-Path $assets 'logo-original.png'))
try {
    foreach ($size in @(32, 80)) {
        $icon = [Drawing.Bitmap]::new($size, $size, [Drawing.Imaging.PixelFormat]::Format32bppArgb)
        $graphics = [Drawing.Graphics]::FromImage($icon)
        $attributes = [Drawing.Imaging.ImageAttributes]::new()
        try {
            $graphics.CompositingMode = [Drawing.Drawing2D.CompositingMode]::SourceCopy
            $graphics.CompositingQuality = [Drawing.Drawing2D.CompositingQuality]::HighQuality
            $graphics.InterpolationMode = [Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
            $graphics.PixelOffsetMode = [Drawing.Drawing2D.PixelOffsetMode]::HighQuality
            $attributes.SetWrapMode([Drawing.Drawing2D.WrapMode]::TileFlipXY)
            $graphics.DrawImage($source, [Drawing.Rectangle]::new(0, 0, $size, $size),
                0, 0, $source.Width, $source.Height, [Drawing.GraphicsUnit]::Pixel, $attributes)
            $path = Join-Path $assets "icon-$size.png"
            $icon.Save($path, [Drawing.Imaging.ImageFormat]::Png)
            $images[$size] = [Convert]::ToBase64String([IO.File]::ReadAllBytes($path))
        }
        finally {
            $attributes.Dispose()
            $graphics.Dispose()
            $icon.Dispose()
        }
    }
}
finally { $source.Dispose() }

$code = @"
// <auto-generated />
// Regenerate from assets\logo-original.png with scripts\Update-Logo.ps1.
namespace FetchXmlLinter.XrmToolBox
{
    internal static class PluginImages
    {
        internal const string Small = "$($images[32])";
        internal const string Big = "$($images[80])";
    }
}
"@
[IO.File]::WriteAllText((Join-Path $root 'src\FetchXmlLinter.XrmToolBox\PluginImages.Generated.cs'),
    $code + [Environment]::NewLine, [Text.UTF8Encoding]::new($false))
